"""FORWARD TEST lifecycle, settlement and statistics.

The properties that make a recorded dataset trustworthy:

* detection freezes the hypothesis, and nothing later can revise it;
* a detected setup is not a filled setup — NO_FILL is tracked separately from
  a loss, because "untradable" and "wrong" are different failures;
* settlement is deterministic and decided by arrival, not by rule order;
* trailing tightens only, and the original invalidation survives it;
* the aggregate statistics use honest denominators;
* bullish and bearish are exact mirrors.
"""

from __future__ import annotations

from dataclasses import FrozenInstanceError, replace

import pytest

from smc.forward_test import (
    DEFAULT_FORWARD_TEST_CONFIG,
    ForwardTestConfig,
    SetupSnapshot,
    advance_position,
    compute_stats,
    cost_in_r,
    default_variants,
    outcome_for,
    entry_zone,
    is_finite_plan,
    open_position,
    outcome_of,
)

T0 = 1_700_000_000.0
CFG = DEFAULT_FORWARD_TEST_CONFIG


def snapshot(direction: str = "bearish", **overrides: object) -> SetupSnapshot:
    """A bearish continuation: enter 100, stop 102, target 94 → 3R.

    The mirror (bullish) is generated by `mirrored` so symmetry is tested
    against exactly the same geometry.
    """
    reference = 100.0
    invalidation = 102.0 if direction == "bearish" else 98.0
    target = 94.0 if direction == "bearish" else 106.0
    low, high = entry_zone(direction, reference, invalidation, CFG)  # type: ignore[arg-type]
    base: dict[str, object] = dict(
        symbol="TST",
        market="perp",
        mode="SCALP",
        direction=direction,
        detected_at=T0,
        state="PULLBACK_COMPLETION",
        tier="HIGH",
        combo="structure+activity",
        families=("PARTICIPATION", "PRICE", "STRUCTURE"),
        score=72.0,
        entry_low=low,
        entry_high=high,
        reference_entry=reference,
        initial_invalidation=invalidation,
        target=target,
        target_kind="equal_lows",
        potential_rr=3.0,
        htf_bias=direction,
        htf_agreement=1.0,
        alignment="aligned",
        alignment_level="HIGH",
        structure_trend="downtrend" if direction == "bearish" else "uptrend",
        headline_event="VOLUME_ANOMALY",
        event_age_seconds=18.0,
        rvol=5.7,
        change_1m_pct=-0.9,
        change_3m_pct=-1.6,
        change_5m_pct=-2.0,
        change_15m_pct=-2.4,
        retrace_frac=0.38,
        pullback_volume_ratio=0.8,
        completion_evidence=("VOLUME_COOLED", "MICRO_CHOCH"),
        micro_choch=True,
        liquidity_target=True,
        engine_version="2.0.0",
        momentum_version="1.0.0",
        events_version="1.1.0",
        context_version="1.0.0",
        forward_test_version="1.0.0",
        config_hash="abcd1234",
        git_sha="deadbeef",
    )
    base.update(overrides)
    return SetupSnapshot(**base)  # type: ignore[arg-type]


def mirrored(price: float, pivot: float = 100.0) -> float:
    """Reflects a price around the entry so a bearish scenario becomes the
    identical bullish one."""
    return 2 * pivot - price


def run(
    setup: SetupSnapshot,
    prices: list[tuple[float, float]],
    config: ForwardTestConfig = CFG,
):
    """Feeds `(offset_seconds, price)` observations and returns the final
    position plus every event emitted."""
    position, events = open_position(setup, T0, setup.reference_entry, config)
    for offset, price in prices:
        position, more = advance_position(setup, position, price, T0 + offset, config)
        events.extend(more)
    return position, events


# ── the hypothesis is frozen ─────────────────────────────────────────────────


def test_a_snapshot_cannot_be_mutated() -> None:
    """Structural, not conventional: the type refuses."""
    setup = snapshot()
    with pytest.raises(FrozenInstanceError):
        setup.target = 90.0  # type: ignore[misc]


def test_settlement_never_revises_the_plan() -> None:
    """The plan after a full winning trade is byte-identical to the plan at
    detection — no retrospective target, no moved invalidation."""
    setup = snapshot()
    before = (setup.reference_entry, setup.initial_invalidation, setup.target, setup.potential_rr)
    position, _ = run(setup, [(30, 100.5), (60, 98.0), (90, 93.5)])
    assert position.status == "TARGET_HIT"
    assert (
        setup.reference_entry,
        setup.initial_invalidation,
        setup.target,
        setup.potential_rr,
    ) == before


def test_the_original_invalidation_survives_trailing() -> None:
    setup = snapshot()
    position, _ = run(setup, [(30, 100.5), (60, 97.0), (90, 96.0)])
    assert position.trailing_active is True
    assert position.active_stop != setup.initial_invalidation
    assert setup.initial_invalidation == 102.0


# ── entry model ──────────────────────────────────────────────────────────────


def test_detection_is_not_a_fill() -> None:
    """The most important line in the module: a setup being detected says
    nothing about whether you could have entered it."""
    setup = snapshot()
    position, events = open_position(setup, T0, 100.0, CFG)
    assert position.status == "PENDING_ENTRY"
    assert position.filled is False
    assert [event.type for event in events] == ["SETUP_CONFIRMED"]


def test_the_entry_zone_extends_toward_the_invalidation() -> None:
    """You wait for a better price; you never chase a worse one."""
    low, high = entry_zone("bearish", 100.0, 102.0, CFG)
    assert low == pytest.approx(100.0)
    assert high > 100.0
    low, high = entry_zone("bullish", 100.0, 98.0, CFG)
    assert high == pytest.approx(100.0)
    assert low < 100.0


def test_price_reaching_the_zone_fills_the_position() -> None:
    setup = snapshot()
    position, events = run(setup, [(30, 100.4)])
    assert position.status == "ACTIVE"
    assert position.entry_price == pytest.approx(100.4)
    assert [e.type for e in events] == ["SETUP_CONFIRMED", "ENTRY_ZONE_TOUCHED", "ENTRY_FILLED"]


def test_a_setup_that_runs_away_never_fills_and_is_not_a_loss() -> None:
    setup = snapshot()
    # Price drops straight to target without ever offering the entry.
    position, events = run(
        setup, [(30, 96.0), (60, 94.0), (CFG.entry_window_seconds + 60, 93.0)]
    )
    assert position.status == "NO_FILL"
    assert position.realized_r == 0.0
    assert position.pending_mfe_pct > 0
    assert "EXPIRED" in [e.type for e in events]


def test_a_no_fill_records_whether_price_ever_reached_the_zone() -> None:
    setup = snapshot()
    position, _ = run(setup, [(30, 100.2), (60, 100.2)])
    assert position.zone_touched_at is not None
    # …and one that never came close.
    away, _ = run(snapshot(), [(30, 96.0), (CFG.entry_window_seconds + 60, 95.0)])
    assert away.zone_touched_at is None
    assert outcome_of(snapshot(), away).touched_zone is False


# ── settlement ───────────────────────────────────────────────────────────────


def test_reaching_the_target_settles_as_a_win() -> None:
    setup = snapshot()
    position, events = run(setup, [(30, 100.4), (60, 94.0)])
    assert position.status == "TARGET_HIT"
    assert position.realized_r > 2.5
    assert position.exit_reason == "target"
    assert "TARGET_HIT" in [e.type for e in events]


def test_losing_the_invalidation_settles_as_a_loss() -> None:
    setup = snapshot()
    position, _ = run(setup, [(30, 100.4), (60, 102.5)])
    assert position.status == "INVALIDATED"
    assert position.realized_r < 0
    assert position.exit_reason == "invalidation"


def test_a_trade_that_goes_nowhere_times_out() -> None:
    setup = snapshot()
    position, _ = run(setup, [(30, 100.4), (CFG.max_holding_seconds + 120, 100.1)])
    assert position.status == "EXPIRED"
    assert position.exit_reason == "timeout"


def test_settlement_is_terminal() -> None:
    setup = snapshot()
    position, _ = run(setup, [(30, 100.4), (60, 94.0)])
    settled = position
    position, events = advance_position(setup, position, 105.0, T0 + 200, CFG)
    assert position == settled
    assert events == []


def test_ordering_follows_arrival_not_rule_order() -> None:
    """Stop first then target is a loss; target first then stop is a win. The
    same two prices, opposite outcomes — decided by which arrived first."""
    stopped, _ = run(snapshot(), [(30, 100.4), (60, 102.5), (90, 94.0)])
    won, _ = run(snapshot(), [(30, 100.4), (60, 94.0), (90, 102.5)])
    assert stopped.status == "INVALIDATED"
    assert won.status == "TARGET_HIT"


# ── trailing ─────────────────────────────────────────────────────────────────


def test_trailing_activates_only_once_the_trade_is_in_profit() -> None:
    setup = snapshot()
    position, events = run(setup, [(30, 100.0), (60, 99.5)])
    assert position.trailing_active is False
    position, more = advance_position(setup, position, 97.5, T0 + 90, CFG)
    assert position.trailing_active is True
    assert "TRAIL_ACTIVATED" in [e.type for e in [*events, *more]]


def test_the_stop_only_ever_tightens() -> None:
    setup = snapshot()
    position, _ = run(setup, [(30, 100.0), (60, 97.0), (90, 96.0)])
    tightened = position.active_stop
    # Price retraces against us: the stop must not follow it back out.
    position, _ = advance_position(setup, position, 99.0, T0 + 120, CFG)
    assert position.active_stop == tightened


def test_every_stop_move_is_preserved() -> None:
    setup = snapshot()
    position, _ = run(setup, [(30, 100.0), (60, 97.0), (90, 96.0), (120, 95.0)])
    assert len(position.trailing_updates) >= 2
    stops = [stop for _, stop in position.trailing_updates]
    # Monotonically tightening for a bearish trade.
    assert stops == sorted(stops, reverse=True)


def test_a_trailed_exit_is_labelled_as_one() -> None:
    setup = snapshot()
    position, _ = run(setup, [(30, 100.0), (60, 96.0), (90, 99.5)])
    assert position.status == "INVALIDATED"
    assert position.exit_reason == "trailing_stop"
    # Trailed out above breakeven: a small win, not the structural loss.
    assert position.realized_r > 0


def test_trailing_can_be_switched_off_entirely() -> None:
    config = replace(CFG, trailing_mode="NONE")
    setup = snapshot()
    position, _ = run(setup, [(30, 100.0), (60, 96.0), (90, 95.0)], config)
    assert position.trailing_active is False
    assert position.active_stop == setup.initial_invalidation


