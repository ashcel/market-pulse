# ── symmetry ─────────────────────────────────────────────────────────────────


def test_bullish_and_bearish_are_exact_mirrors() -> None:
    bear = snapshot("bearish")
    bull = snapshot("bullish")
    path = [(30, 100.4), (60, 98.0), (90, 94.0)]
    bear_position, bear_events = run(bear, path)
    bull_position, bull_events = run(bull, [(t, mirrored(p)) for t, p in path])

    assert bear_position.status == bull_position.status == "TARGET_HIT"
    # Gross R mirrors exactly; net R only to within the cost of the price
    # difference, because a fee is a share of price and mirroring around 100
    # fills the two sides at 100.4 and 99.6.
    assert bear_position.gross_r == pytest.approx(bull_position.gross_r)
    assert bear_position.realized_r == pytest.approx(bull_position.realized_r, rel=1e-3)
    assert bear_position.mfe_r == pytest.approx(bull_position.mfe_r)
    assert [e.type for e in bear_events] == [e.type for e in bull_events]


def test_mirrored_losses_match_too() -> None:
    path = [(30, 100.4), (60, 102.5)]
    bear, _ = run(snapshot("bearish"), path)
    bull, _ = run(snapshot("bullish"), [(t, mirrored(p)) for t, p in path])
    assert bear.status == bull.status == "INVALIDATED"
    assert bear.gross_r == pytest.approx(bull.gross_r)
    assert bear.realized_r == pytest.approx(bull.realized_r, rel=1e-3)


# ── determinism ──────────────────────────────────────────────────────────────


def test_the_same_observations_always_produce_the_same_record() -> None:
    path = [(30, 100.4), (60, 98.0), (90, 96.0), (120, 94.0)]
    first, first_events = run(snapshot(), path)
    second, second_events = run(snapshot(), path)
    assert first == second
    assert [(e.type, e.ts, e.price) for e in first_events] == [
        (e.type, e.ts, e.price) for e in second_events
    ]


def test_a_degenerate_plan_is_rejected_before_it_is_recorded() -> None:
    assert is_finite_plan(100.0, 102.0, 94.0) is True
    assert is_finite_plan(100.0, 100.0, 94.0) is False
    assert is_finite_plan(100.0, 102.0, 100.0) is False
    assert is_finite_plan(0.0, 102.0, 94.0) is False
    assert is_finite_plan(float("inf"), 102.0, 94.0) is False


# ── aggregate statistics ─────────────────────────────────────────────────────


def rows(*items: tuple[str, float, float, float]) -> list[tuple[str, float, float, float]]:
    return list(items)


def test_win_rate_counts_fills_and_fill_rate_counts_setups() -> None:
    """Mixing these denominators is the easiest way to make an untradable
    strategy look tradable."""
    stats = compute_stats(
        rows(
            ("TARGET_HIT", 3.0, 3.0, -0.2),
            ("INVALIDATED", -1.0, 0.4, -1.0),
            ("NO_FILL", 0.0, 0.0, 0.0),
            ("NO_FILL", 0.0, 0.0, 0.0),
        )
    )
    assert stats.total == 4
    assert stats.filled == 2
    assert stats.fill_rate == pytest.approx(0.5)
    assert stats.win_rate == pytest.approx(0.5)
    assert stats.no_fill_rate == pytest.approx(0.5)


def test_open_setups_are_excluded_from_settled_rates() -> None:
    stats = compute_stats(rows(("PENDING_ENTRY", 0.0, 0.0, 0.0), ("TARGET_HIT", 2.0, 2.0, 0.0)))
    assert stats.open == 1
    assert stats.fill_rate == pytest.approx(1.0)
    assert stats.win_rate == pytest.approx(1.0)


def test_expectancy_is_per_recorded_setup_not_per_fill() -> None:
    """A setup you could not enter still consumed the opportunity."""
    stats = compute_stats(rows(("TARGET_HIT", 3.0, 3.0, 0.0), ("NO_FILL", 0.0, 0.0, 0.0)))
    assert stats.average_r == pytest.approx(3.0)
    assert stats.expectancy == pytest.approx(1.5)


def test_profit_factor_and_drawdown() -> None:
    stats = compute_stats(
        rows(
            ("TARGET_HIT", 3.0, 3.0, -0.3),
            ("INVALIDATED", -1.0, 0.2, -1.0),
            ("INVALIDATED", -1.0, 0.1, -1.0),
            ("TARGET_HIT", 2.0, 2.0, -0.4),
        )
    )
    assert stats.profit_factor == pytest.approx(2.5)
    assert stats.total_r == pytest.approx(3.0)
    assert stats.max_drawdown_r == pytest.approx(-2.0)


def test_empty_statistics_are_zeroed_not_undefined() -> None:
    stats = compute_stats([])
    assert stats.total == 0
    assert stats.win_rate == 0.0
    assert stats.profit_factor == 0.0
    assert stats.expectancy == 0.0


